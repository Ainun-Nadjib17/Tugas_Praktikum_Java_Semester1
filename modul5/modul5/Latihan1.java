public class Latihan1 {
    public static void main(String[] args) {
        // 1. Mencetak bilangan dari 1 hingga 10
        System.out.println("Bilangan 1 hingga 10:");
        for (int i = 1; i <= 10; i++) {
            System.out.println(i);
        }

        // 2. Modifikasi: mencetak bilangan ganjil dari 1 hingga 10
        System.out.println("Bilangan ganjil 1 hingga 10:");
        for (int i = 1; i <= 10; i += 2) {
            System.out.println(i);
        }
    }
}
